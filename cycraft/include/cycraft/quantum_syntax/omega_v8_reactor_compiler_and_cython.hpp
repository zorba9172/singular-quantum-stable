    static Ci95Metric compute_ci95(const std::vector<double>& samples) noexcept {
        Ci95Metric m{};
        if (samples.empty()) return m;
        const double n = static_cast<double>(samples.size());
        m.mean = std::accumulate(samples.begin(), samples.end(), 0.0) / n;
        double sq = 0.0;
        for (double v : samples) sq += (v - m.mean) * (v - m.mean);
        m.stddev = std::sqrt(sq / std::max(1.0, n - 1.0));
        const double hw = 1.96 * (m.stddev / std::sqrt(n));
        m.ci95_low = m.mean - hw; m.ci95_high = m.mean + hw;
        return m;
    }

